import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { deflateRawSync } from 'node:zlib';

const folder = new URL('../src/i18n/messages/', import.meta.url);
const source = JSON.parse(readFileSync(new URL('pt-BR.json', folder), 'utf8'));
const keys = Object.keys(source).sort();
const packed = {};
let rawBytes = 0;
for (const file of readdirSync(folder).filter(file => file.endsWith('.json') && file !== 'locations.json')) {
  const locale = file.slice(0, -5);
  const messages = JSON.parse(readFileSync(new URL(file, folder), 'utf8'));
  for (const key of keys) {
    const text = messages[key];
    if (typeof text !== 'string' || !text.trim()) throw new Error(`${locale}: missing ${key}`);
    const placeholders = value => [...value.matchAll(/\{p\d+\}/g)].map(match => match[0]).sort().join(',');
    if (placeholders(text) !== placeholders(source[key])) throw new Error(`${locale}: invalid placeholders in ${key}`);
    if (/__SSHTKEEP|@@SSHT/.test(text)) throw new Error(`${locale}: unprocessed token in ${key}`);
  }
  const values = locale === 'pt-PT'
    ? Object.fromEntries(keys.flatMap((key, index) => messages[key] === source[key] ? [] : [[index, messages[key]]]))
    : keys.map(key => messages[key]);
  const bytes = Buffer.from(JSON.stringify(values));
  rawBytes += bytes.length;
  packed[locale] = deflateRawSync(bytes, { level: 9 }).toString('base64');
}
if (Buffer.byteLength(JSON.stringify(packed)) > rawBytes / 2) throw new Error('Translation payload must retain at least 50% compression.');
writeFileSync(new URL('data.ts', folder), '// Generated by npm run i18n:pack. Do not edit.\n' +
  'export const MESSAGE_KEYS = ' + JSON.stringify(keys) + ' as const;\n' +
  'export const PACKED_MESSAGES: Record<string, string> = ' + JSON.stringify(packed) + ';\n');
console.log(`${keys.length} messages × ${Object.keys(packed).length} locales; ${(rawBytes / 1024).toFixed(1)} KiB JSON → ${(Buffer.byteLength(JSON.stringify(packed)) / 1024).toFixed(1)} KiB packed, offline.`);
